#!/usr/bin/env python3
"""Export the lead_a3 certificate of one pair to lean/LeadAData.lean (default [3] -> [1,4]).
Usage (needs numpy): python3 lean/export_leada.py [S1 S2]   e.g.  3 1,4"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "experiments"))
from lead_a3 import Pair

def bl(l):
    return "[" + ", ".join("true" if x else "false" for x in l) + "]"

def main():
    a = sys.argv[1:]
    S1 = tuple(int(x) for x in (a[0] if a else "3").split(","))
    S2 = tuple(int(x) for x in (a[1] if a else "1,4").split(","))
    P = Pair(S1, S2)
    c = P.certify()
    M = max(S1)
    n = c["a0_window"] + c["q"] + M
    assert len(P.rows) >= n
    rows = ",\n".join(f"  {{ pre := {bl(r.pre)}, cyc := {bl(r.cyc)} }}" for r in P.rows[:n])
    tag = "_".join("".join(map(str, S)) for S in (S1, S2))
    out = f"""-- generated by lean/export_leada.py from lead_a3.Pair({list(S1)}, {list(S2)}).certify(); do not edit
-- python certificate: {c}
import LeadACheck
namespace LeadA

def cert_{tag} : Cert := {{
  gpre := {c['gpre']}, gper := {c['gper']}, q := {c['q']}, A0 := {c['A0']}, a0 := {c['a0_window']},
  p := {c['p']}, T := {c['T']},
  rows := [
{rows}] }}

end LeadA
"""
    open(os.path.join(HERE, "LeadAData.lean"), "w").write(out)
    print("wrote LeadAData.lean", c)

main()
