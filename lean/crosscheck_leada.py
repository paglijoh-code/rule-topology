#!/usr/bin/env python3
"""Run from anywhere: writes lean/LeadACrossData.lean and lean/LeadACross.lean's theorem block.
Solver = lead_a2.solve2 (ground truth), a, b <= N, 1 = P."""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "experiments"))
from lead_a2 import solve2

N = 40
PAIRS = [((3,), (1, 4)), ((1, 3), (2, 4)), ((2, 3, 4), (2, 3))]

def lean_bool_rows(P):
    return "[\n" + ",\n".join("  [" + ", ".join("true" if P[a][b] else "false" for b in range(N + 1)) + "]"
                              for a in range(N + 1)) + "]"

def nm(S1, S2):
    return "_".join("".join(map(str, S)) for S in (S1, S2))

def main():
    out = ["-- generated by lean/crosscheck_leada.py from lead_a2.solve2; do not edit",
           "namespace LeadA", ""]
    thms = []
    for S1, S2 in PAIRS:
        P = solve2(set(S1), set(S2), N)
        n = nm(S1, S2)
        out.append(f"def data_{n} : List (List Bool) := {lean_bool_rows(P)}\n")
        thms.append(f"/-- Lean outcome = lead_a2 solver on all a, b <= {N}, S1 = {list(S1)}, S2 = {list(S2)}. -/\n"
                    f"theorem small_{n} : outcomeOk {list(S1)} {list(S2)} 10 data_{n} = true := by decide +kernel\n\n"
                    f"/-- Same, the table `outcome` reads from, all a, b <= {N}. -/\n"
                    f"theorem cross_{n} : crossOk {list(S1)} {list(S2)} {N} data_{n} = true := by decide +kernel\n")
    out.append("end LeadA\n")
    open(os.path.join(HERE, "LeadACrossData.lean"), "w").write("\n".join(out))
    sg = [f"theorem sg_{nm(S1,S2)} : sgOk {list(S2)} {N} = true := by decide +kernel\n" for S1, S2 in PAIRS]
    body = "\n".join(thms) + "\n" + "\n".join(sg)
    path = os.path.join(HERE, "LeadACrossThms.lean")
    open(path, "w").write("-- generated by lean/crosscheck_leada.py; do not edit\nimport LeadACross\nnamespace LeadA\n\n"
                          "set_option maxRecDepth 100000\n\n" + body + "\n#print axioms cross_3_14\nend LeadA\n")
    print("wrote", N, "x", N, "data for", PAIRS)

main()
